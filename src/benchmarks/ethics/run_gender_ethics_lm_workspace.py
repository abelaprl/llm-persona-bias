def create_notebook(bundle: Path, path: Path, execute: bool):
    import nbformat as nbf
    from nbclient import NotebookClient
    from jupyter_client import KernelManager
    from jupyter_client.kernelspec import KernelSpec

    if path.exists():
        raise FileExistsError(path)
    notebook = nbf.v4.new_notebook(cells=notebook_cells(bundle))
    notebook.metadata.kernelspec = dict(name="python3", display_name="Python 3", language="python")
    if execute:
        manager = KernelManager(kernel_name="python3")
        manager._kernel_spec = KernelSpec(argv=[sys.executable, "-m", "ipykernel_launcher", "-f", "{connection_file}"],
                                          display_name="Python 3", language="python")
        NotebookClient(notebook, km=manager, timeout=600, resources={"metadata": {"path": str(path.parent)}}).execute()
    nbf.validate(notebook)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as handle:
        nbf.write(notebook, handle)
    codes = [c for c in notebook.cells if c.cell_type == "code"]
    return {"path": str(path), "cells": len(notebook.cells), "code_cells": len(codes),
            "executed": sum(c.execution_count is not None for c in codes),
            "errors": sum(o.output_type == "error" for c in codes for o in c.outputs)}


