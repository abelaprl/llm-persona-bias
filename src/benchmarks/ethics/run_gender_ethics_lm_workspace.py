def sha256(path: Path) -> str:
    with path.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def cached_pair_reader(original):
    """Cache numeric vectors and key joins for one group, preserving left order."""
    import numpy as np
    import pandas as pd

    cache = {}

    def read(group, left_persona, right_persona, value_col, *, require_both_correct=False):
        if require_both_correct:
            return original(group, left_persona, right_persona, value_col,
                            require_both_correct=True)
        if cache.get("group") is not group:
            cache.clear()
            cache["group"] = group
            cache["positions"] = {
                persona: np.flatnonzero(group.persona.eq(persona).to_numpy())
                for persona in group.persona.unique()}
            cache["joins"], cache["values"] = {}, {}
        positions = cache["positions"]
        empty = np.array([], dtype=int)
        key = (left_persona, right_persona)
        if key not in cache["joins"]:
            left_positions = positions.get(left_persona, empty)
            right_positions = positions.get(right_persona, empty)
            left_keys = pd.Index(group.question_id.iloc[left_positions])
            right_keys = pd.Index(group.question_id.iloc[right_positions])
            if not left_keys.is_unique or not right_keys.is_unique:
                raise ValueError("Duplicate question key in persona pair")
            indexer = right_keys.get_indexer(left_keys)
            found = indexer >= 0
            cache["joins"][key] = (np.flatnonzero(found), indexer[found])
        vectors = []
        for persona in key:
            vector_key = (persona, value_col)
            if vector_key not in cache["values"]:
                cache["values"][vector_key] = pd.to_numeric(
                    group[value_col].iloc[positions.get(persona, empty)],
                    errors="coerce").to_numpy(float)
            vectors.append(cache["values"][vector_key])
        left_indices, right_indices = cache["joins"][key]
        left, right = vectors[0][left_indices], vectors[1][right_indices]
        valid = ~pd.isna(left) & ~pd.isna(right)
        return left[valid], right[valid]

    return read


def write_json(path: Path, data) -> None:
    with path.open("x", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2,
                  default=lambda v: v.item() if hasattr(v, "item") else str(v))


def validate_measurements(frame, marker_ids) -> dict:
    """Reject missing-as-zero, inconsistent densities and duplicate keys."""
    import numpy as np
    from src.benchmarks.ethics.build_gender_ethics_linguistic_markers_v1_4 import _bool_series

    if frame.duplicated(["model_id", "subset", "question_id", "persona"]).any():
        raise ValueError("Duplicate response key")
    available = _bool_series(frame["text_available"])
    if not frame.loc[available, "word_count"].gt(0).all():
        raise ValueError("Available text must have positive word count")
    for marker in marker_ids:
        cols = [f"{marker}__{suffix}" for suffix in ("count", "density", "present")]
        values = frame[cols]
        if not values.loc[~available].isna().all().all():
            raise ValueError(f"Unavailable text encoded as marker values: {marker}")
        present = values.loc[available]
        if not present.notna().all().all():
            raise ValueError(f"Missing measurement on available text: {marker}")
        count = present[cols[0]]
        if not (count.ge(0) & count.mod(1).eq(0)).all():
            raise ValueError(f"Invalid counts: {marker}")
        if not np.allclose(present[cols[1]], 100 * count / frame.loc[available, "word_count"]):
            raise ValueError(f"Density/count mismatch: {marker}")
        if not present[cols[2]].eq(count.gt(0).astype(int)).all():
            raise ValueError(f"Presence/count mismatch: {marker}")
    return {"valid": True, "rows": len(frame), "markers_checked": len(marker_ids),
            "available": int(available.sum()), "unavailable": int((~available).sum())}


def availability_checks(frame):
    """Use paired Cochran Q, not an independence test on repeated responses."""
    import numpy as np
    import pandas as pd
    from src.core.linguistic_markers.statistics import _cochran_q, holm_adjust

    work = frame.copy()
    events = {"text_unavailable": ~work["text_available"].astype(bool),
              "answer_abstain": work["answer_status"].eq("abstain"),
              "answer_missing": work["answer_status"].eq("missing")}
    rows = []
    for outcome, values in events.items():
        work["event"] = values.astype(int)
        for (model, subset), group in work.groupby(["model_id", "subset"]):
            matrix = group.pivot(index="question_id", columns="persona", values="event")
            if matrix.shape[1] != 9 or matrix.isna().any().any():
                raise ValueError("Availability diagnostic requires nine complete scenarios")
            statistic, p = _cochran_q(matrix.to_numpy(float))
            rates = matrix.mean()
            rows.append(dict(model_id=model, subset=subset, outcome_id=outcome,
                             n_complete_blocks=len(matrix), test_used="cochran_q",
                             statistic=statistic, p_raw=p,
                             min_rate=float(rates.min()), max_rate=float(rates.max()),
                             rate_range_pp=float(100 * np.ptp(rates)),
                             interpretation="paired_status_diagnostic_not_causal_parser_bias"))
    result = pd.DataFrame(rows)
    result["p_holm"] = holm_adjust(result["p_raw"])
    result["holm_family_size"] = len(result)
    return result


def add_diagnostics(bundle: Path, marker_dir: Path, package: Path):
    import numpy as np
    import pandas as pd
    from src.benchmarks.ethics import build_gender_ethics_linguistic_markers_v1_5 as builder
    from src.benchmarks.ethics.build_gender_ethics_linguistic_markers_v1_4 import _bool_series

    registry = pd.read_csv(marker_dir / "marker_registry.csv")
    columns = ["model_id", "subset", "question_id", "persona", "text_available",
               "answer_status", "word_count"]
    columns += [f"{marker}__{suffix}" for marker in registry.marker_id
                for suffix in ("count", "density", "present")]
    frame = pd.read_csv(marker_dir / "response_level_markers.csv.gz",
                        usecols=columns, low_memory=False)
    frame["text_available"] = _bool_series(frame["text_available"])
    checks = validate_measurements(frame, builder.AUDITED_MARKER_IDS)
    checks_path = bundle / "workspace_measurement_validation.json"
    write_json(checks_path, checks)
    availability_checks(frame).to_csv(bundle / "workspace_paired_availability_tests.csv", index=False)
    keys = ["model_id", "persona", "subset"]
    status = frame.assign(total=1, committed=frame.answer_status.eq("committed").astype(int),
                          abstain=frame.answer_status.eq("abstain").astype(int),
                          missing=frame.answer_status.eq("missing").astype(int),
                          available=frame.text_available.astype(int))
    coverage = status.groupby(keys)[["total", "committed", "abstain", "missing", "available"]].sum().reset_index()
    for state, rate in (("committed", "commit_rate"), ("abstain", "abstain_rate"),
                        ("missing", "missing_rate"), ("available", "visible_text_rate")):
        coverage[rate] = coverage[state] / coverage.total
    coverage.to_csv(bundle / "workspace_coverage.csv", index=False)
    # Keep additional moral/response markers descriptive; no new rule is added.
    registry.to_csv(bundle / "workspace_full_marker_registry.csv", index=False)
    registry[~registry.marker_id.isin(builder.AUDITED_MARKER_IDS)].to_csv(
        bundle / "workspace_supplementary_marker_registry.csv", index=False)
    rows = []
    for marker in registry.marker_id:
        cols = [f"{marker}__{suffix}" for suffix in ("count", "density", "present")]
        if not set(cols).issubset(frame):
            raise ValueError(f"Missing stored marker: {marker}")
        selected = frame.loc[frame.text_available, keys + cols]
        grouped = selected.groupby(keys).agg(n_text=(cols[0], "size"),
                                             raw_count=(cols[0], "sum"),
                                             responses_with_marker=(cols[2], "sum"),
                                             mean_density=(cols[1], "mean"),
                                             median_density=(cols[1], "median")).reset_index()
        grouped["marker_id"] = marker
        grouped["prevalence"] = grouped.responses_with_marker / grouped.n_text
        grouped["result_status"] = "candidate"
        rows.append(grouped)
    pd.concat(rows, ignore_index=True).to_csv(bundle / "workspace_marker_descriptives.csv", index=False)
    baseline = REPORTS / "linguistic_markers/analysis/gender_ethics_linguistic_markers_v1_4_candidate_r4_20260826"
    comparison = []
    for name in sorted(bundle.glob("paired_numeric_*_all_text.csv")):
        old = baseline / name.name
        if not old.is_file():
            continue
        before, after = pd.read_csv(old), pd.read_csv(name)
        ids = [c for c in ("model_id", "benchmark", "subset", "identity", "outcome_id", "contrast_id") if c in before]
        joined = before.merge(after, on=ids, suffixes=("_old", "_new"), how="outer", indicator=True, validate="one_to_one")
        for metric in ("n_pairs", "n_nonzero", "rank_biserial", "p_raw", "p_holm", "ci_low", "ci_high"):
            delta = (joined[metric + "_new"] - joined[metric + "_old"]).abs()
            comparison.append(dict(table=name.name, metric=metric, old_rows=len(before),
                                   new_rows=len(after), matched_rows=int(joined._merge.eq("both").sum()),
                                   changed_rows=int((~np.isclose(joined[metric+"_old"], joined[metric+"_new"], equal_nan=True)).sum()),
                                   max_abs_difference=float(delta.max())))
    pd.DataFrame(comparison).to_csv(bundle / "workspace_previous_core_comparison.csv", index=False)
    inputs = [marker_dir / f for f in ("response_level_markers.csv.gz", "marker_registry.csv", "manifest.json")]
    inputs += list(package.glob("*.py"))
    inputs += [Path(__file__), ROOT / "src/benchmarks/ethics/build_gender_ethics_linguistic_markers_v1_4.py",
               ROOT / "src/benchmarks/ethics/build_gender_ethics_linguistic_markers_v1_5.py"]
    write_json(bundle / "workspace_provenance.json", {
        "marker_package": str(package.relative_to(ROOT)), "marker_extraction_rerun": False,
        "pair_reader": "One-group key/vector cache; same pair order, NA filtering, tests and seeds as original",
        "human_labels_generated": False, "source_sha256": {str(p.relative_to(ROOT)): sha256(p) for p in inputs},
        "availability_test": "Cochran Q across nine paired scenarios; Holm over all 72 diagnostic tests",
        "limitation": "Availability and abstention are different events; significance does not establish parser-caused bias.",
    })


